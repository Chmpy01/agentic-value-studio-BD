import asyncio,json
from pathlib import Path
from playwright.async_api import async_playwright
r=Path(__file__).parent
async def main():
 async with async_playwright() as p:
  b=await p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
  pg=await b.new_page(viewport={'width':1536,'height':960},device_scale_factor=1)
  errs=[];pg.on('pageerror',lambda x:errs.append(str(x)))
  await pg.set_content((r/'index.html').read_text(),wait_until='domcontentloaded',timeout=30000)
  await pg.wait_for_timeout(450)
  await pg.screenshot(path=str(r/'preview_live.png'))
  print('INITIAL',await pg.locator('.run-detail h2').inner_text(),'BUTTONS',await pg.locator('.flowstep').count())
  for step in range(1,6):
   await pg.locator('#next').click()
  print('APPROVAL_REQUIRED',await pg.locator('.approval').count(),'STEP',await pg.locator('.run-detail h2').inner_text())
  await pg.locator('#next').click()
  print('GATED_AT',await pg.locator('.run-detail h2').inner_text())
  await pg.locator('[data-approve="approved"]').click()
  for _ in range(3):await pg.locator('#next').click()
  print('AFTER_APPROVAL',await pg.locator('.run-detail h2').inner_text(),'TRACE',await pg.evaluate('window.__CVS_TEST__.state.log.length'))
  await pg.locator('[data-tab="agents"]').click()
  await pg.screenshot(path=str(r/'preview_agents.png'))
  print('AGENT_TILES',await pg.locator('.agent-tile').count())
  await pg.locator('[data-agent="guard"]').first.click()
  print('AGENT_SELECTED',await pg.locator('.architecture h2').inner_text())
  await pg.locator('[data-tab="value"]').click()
  await pg.screenshot(path=str(r/'preview_value.png'))
  print('LEDGER_TITLE',await pg.locator('section h2').inner_text())
  await pg.locator('[data-tab="contracts"]').click()
  await pg.screenshot(path=str(r/'preview_contracts.png'))
  await pg.locator('[data-contract="permit"]').click()
  print('PERMIT',('SIMULATION_ONLY' in (await pg.locator('#sampleContract').inner_text())))
  await pg.locator('#scenario').select_option('runtime-retail')
  await pg.locator('[data-tab="live"]').click()
  print('RETAIL',await pg.locator('.inset').inner_text())
  await pg.locator('#scenario').select_option('runtime-manufacturing')
  print('MANUFACTURING',await pg.locator('.inset').inner_text())
  mobile=await b.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
  mobile.on('pageerror',lambda x:errs.append(str(x)))
  await mobile.set_content((r/'index.html').read_text(),wait_until='domcontentloaded',timeout=30000)
  await mobile.screenshot(path=str(r/'preview_mobile.png'))
  print('MOBILE_X_OVERFLOW',await mobile.evaluate('document.documentElement.scrollWidth > window.innerWidth'))
  print('PAGE_ERRORS',errs)
  await b.close()
asyncio.run(main())
